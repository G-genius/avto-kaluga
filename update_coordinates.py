def update_coordinates():

    conn = get_connection()
    cursor = conn.cursor()

    updated = 0
    not_found = 0

    for (
        display_name,
        brand,
        address
    ), (
        latitude,
        longitude
    ) in COORDINATES.items():

        cursor.execute("""
            SELECT id
            FROM stations
            WHERE display_name = ?
            AND brand = ?
            AND address = ?
            LIMIT 1
        """, (
            display_name,
            brand,
            address,
        ))

        station = cursor.fetchone()

        if station:

            cursor.execute("""
                UPDATE stations
                SET
                    latitude = ?,
                    longitude = ?,
                    active = 1
                WHERE id = ?
            """, (
                latitude,
                longitude,
                station[0],
            ))

            print(
                f"✅ {display_name} — {brand}"
            )

            updated += 1

        else:

            print(
                f"⚠️ Не найдена: "
                f"{display_name} — "
                f"{brand} — "
                f"{address}"
            )

            not_found += 1

    conn.commit()
    conn.close()

    print()
    print("================================")
    print("КООРДИНАТЫ ОБНОВЛЕНЫ")
    print(f"Обновлено: {updated}")
    print(f"Не найдено: {not_found}")
    print("================================")


if __name__ == "__main__":
    update_coordinates()
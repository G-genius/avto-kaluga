def get_post_index():

    """
    3 поста в день:

    09:00 → первый
    14:00 → второй
    17:00 → третий

    Каждый новый день начинается
    со следующих трёх постов.
    """

    now = datetime.now(MSK)

    # Количество дней от фиксированной даты.
    # Благодаря этому порядок стабилен после перезапуска бота.
    start_date = datetime(2026, 1, 1).date()

    day_number = (
        now.date() - start_date
    ).days

    hour = now.hour

    if hour < 14:
        slot = 0

    elif hour < 17:
        slot = 1

    else:
        slot = 2

    index = (
        day_number * 3 + slot
    ) % len(POSTS)

    return index


